// Concatenate docs/core.js + apps-script/Code.gs into one file to paste into the Apps Script editor.
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..');
const core = fs.readFileSync(path.join(root, 'docs/core.js'), 'utf8').replace(/\nif \(typeof module[^\n]*\n?/, '\n');
const code = fs.readFileSync(path.join(root, 'apps-script/Code.gs'), 'utf8');
fs.writeFileSync(path.join(root, 'apps-script/ALL-IN-ONE.gs'), '/* GENERATED by tools/build-gas.js — do not edit; edit docs/core.js + apps-script/Code.gs */\n' + core + '\n\n' + code);
console.log('apps-script/ALL-IN-ONE.gs written');
